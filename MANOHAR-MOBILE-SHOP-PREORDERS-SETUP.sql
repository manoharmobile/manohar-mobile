-- MANOHAR MOBILE SHOP: customer pre-order requests + product photo storage
-- Run once in Supabase SQL Editor for project qonhrxgewrrtfvuicdzw.

create table if not exists public.preorders (
  id bigint generated by default as identity primary key,
  customer_id uuid null references auth.users(id) on delete set null,
  customer_name text not null check (char_length(customer_name) between 1 and 80),
  customer_phone text not null check (customer_phone ~ '^[6-9][0-9]{9}$'),
  details text not null check (char_length(details) between 1 and 1500),
  image_path text null,
  status text not null default 'New' check (status in ('New','Contacted','Completed','Cancelled')),
  created_at timestamptz not null default now()
);

alter table public.preorders enable row level security;

drop policy if exists "Anyone can submit a pre-order" on public.preorders;
create policy "Anyone can submit a pre-order"
on public.preorders for insert to anon, authenticated
with check (
  (customer_id is null or customer_id = auth.uid())
  and char_length(customer_name) between 1 and 80
  and customer_phone ~ '^[6-9][0-9]{9}$'
  and char_length(details) between 1 and 1500
);

drop policy if exists "Admins can read pre-orders" on public.preorders;
create policy "Admins can read pre-orders"
on public.preorders for select to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

drop policy if exists "Admins can update pre-orders" on public.preorders;
create policy "Admins can update pre-orders"
on public.preorders for update to authenticated
using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'))
with check (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));

-- Public bucket is needed so the shop can attach a viewable photo link to its WhatsApp alert.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('preorder-images', 'preorder-images', true, 5242880, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public = true, file_size_limit = 5242880,
  allowed_mime_types = array['image/jpeg','image/png','image/webp','image/gif'];

drop policy if exists "Public can upload pre-order photos" on storage.objects;
create policy "Public can upload pre-order photos"
on storage.objects for insert to anon, authenticated
with check (bucket_id = 'preorder-images' and (storage.foldername(name))[1] in ('guest', auth.uid()::text));

drop policy if exists "Public can view pre-order photos" on storage.objects;
create policy "Public can view pre-order photos"
on storage.objects for select to anon, authenticated
using (bucket_id = 'preorder-images');

drop policy if exists "Admins can delete pre-order photos" on storage.objects;
create policy "Admins can delete pre-order photos"
on storage.objects for delete to authenticated
using (bucket_id = 'preorder-images' and exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'));
